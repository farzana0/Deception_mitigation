"""Path binding and workspace layout for the CLI.

The experiment library in steering/ and scripts/ is reused unchanged. It addresses its inputs through
module-level ROOT (weights, datasets, upstream repos) and RUN (per-run outputs) paths, so the CLI
builds a small workspace and points those globals at it instead of editing the library.
"""
import gzip, hashlib, json, shutil, sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
CONDITIONS = ['baseline', 'caa', 'sttp', 'rank2', 'pooled']


def repo_path(value):
    path = Path(str(value))
    return path if path.is_absolute() else REPO / path


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def read_bytes(path):
    """Read a stored evidence file, transparently decompressing '.gz'."""
    path = Path(path)
    return gzip.decompress(path.read_bytes()) if path.suffix == '.gz' else path.read_bytes()


def jsonl(path):
    return [json.loads(line) for line in read_bytes(path).splitlines()]


def bind(root, run):
    """Point ROOT/RUN of every imported steering module at this workspace."""
    for name, module in list(sys.modules.items()):
        if name.startswith('steering.'):
            if hasattr(module, 'ROOT'):
                module.ROOT = Path(root)
            if hasattr(module, 'RUN'):
                module.RUN = Path(run)


def link(target, source):
    """Symlink target -> source; an existing link must already point there."""
    if target.is_symlink():
        assert target.resolve() == Path(source).resolve(), f'{target} points elsewhere; use a new run dir'
        return
    target.parent.mkdir(parents=True, exist_ok=True)
    target.symlink_to(source)


def check_locked(cfg):
    """Fail fast if a YAML drifts from the locked settings, fit, revisions or rubric pin."""
    assert cfg.seed == 42, 'seed 42 is fixed in steering.experiment.load and the judge requests'
    if cfg.task.name in ('infer', 'generate'):  # imports torch/transformers; skipped for offline tasks
        from steering import experiment
        assert cfg.model.revision == experiment.REVISION, 'model revision differs from steering.experiment.REVISION'
    iv = cfg.intervention
    locked = json.loads(repo_path(iv.locked_settings).read_text())
    if iv.name.startswith('cp_'):
        assert iv.setting.condition == iv.name and iv.setting.strength == locked['shared_strength']
    else:
        assert dict(iv.setting) == locked['settings'][iv.name], f'{iv.name} setting differs from locked settings'
    assert sha256(repo_path(iv.fit)) == locked['fit_sha256'], 'steering fit hash differs from lock'
    judge = json.loads(repo_path(cfg.judge_model.metadata).read_text())
    assert (judge['model'], judge['revision']) == (cfg.judge_model.model, cfg.judge_model.revision)
    assert cfg.judge_model.endpoint == 'http://127.0.0.1:8001/v1/chat/completions', 'endpoint is fixed in grade_pilot'
    pin = json.loads(repo_path(cfg.judge_rubric.pin).read_text())
    assert pin['commit'] == cfg.judge_rubric.revision, 'rubric revision differs from the official MASK pin'
    assert pin['local_primary']['revision'] == cfg.judge_model.revision, 'judge revision differs from the pin'
    return locked


def run_workspace(cfg):
    """Workspace for fresh runs: <run>/root holds links to weights/data/repos, <run>/steering_run the outputs."""
    run = Path(cfg.paths.run)
    root, steering_run = run / 'root', run / 'steering_run'
    link(root / 'models/Qwen3.5-9B', cfg.model.local_dir)
    link(root / 'data', cfg.paths.data_root)
    link(root / 'repos', cfg.paths.repos_root)
    steering_run.mkdir(parents=True, exist_ok=True)
    iv = cfg.intervention
    for source, name in [(iv.fit, 'fit.pt'), (iv.locked_settings, 'locked_settings.json'),
                         (cfg.judge_model.metadata, 'judge_model.json')]:
        target = steering_run / name
        if target.exists():
            assert sha256(target) == sha256(repo_path(source)), f'{target} differs from {source}; use a new run dir'
        else:
            shutil.copy2(repo_path(source), target)
    return root, steering_run


def materialize_package(manifest_path, package, exclude_prefix):
    """Recreate the frozen package's input layout from evidence/, verifying every SHA256.

    Files under exclude_prefix (the frozen outputs used as the comparison target) are not copied,
    so every compared output must be regenerated by the rebuild.
    """
    manifest = json.loads(repo_path(manifest_path).read_text())
    shutil.rmtree(package, ignore_errors=True)
    inputs = [r for r in manifest['files'] if not r['repo_path'].startswith(exclude_prefix)]
    for record in inputs:
        data = read_bytes(repo_path(record['repo_path']))
        assert hashlib.sha256(data).hexdigest() == record['sha256'], f"evidence hash mismatch: {record['repo_path']}"
        target = package / record['package_path']
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
    return len(inputs)
